#!/usr/bin/env python3
"""Compile an offscreen probe against an existing production SwiftlightVideo build."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build-dir", type=Path, default=Path(".build/debug"))
    parser.add_argument("--fixture", type=Path, required=True)
    parser.add_argument("--fps", type=float, default=240)
    parser.add_argument("--frames", type=int, default=480)
    parser.add_argument("--warmup", type=int, default=120)
    parser.add_argument("--depth", type=int, choices=[8, 10], default=10)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--compile-only", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    build = args.build_dir.resolve()
    if not (build / "description.json").is_file():
        parser.error("Use a native SwiftPM build directory: swift build --build-system native --product swiftlight-replay")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    directory = args.output.resolve().parent / (args.output.stem + "-build")
    directory.mkdir(parents=True, exist_ok=True)
    description = json.loads((build / "description.json").read_text())
    arguments = next(value["otherArguments"] for key, value in description["swiftCommands"].items()
                     if key.startswith("C.SwiftlightVideo-"))
    target = arguments[arguments.index("-target") + 1]
    swiftc = subprocess.check_output(["xcrun", "--find", "swiftc"], text=True).strip()
    sdk = subprocess.check_output(["xcrun", "--sdk", "macosx", "--show-sdk-path"], text=True).strip()
    source = root / "scripts/pyrowave-benchmark-harness.swift"
    executable = directory / "pyrowave-benchmark"
    objects = sorted((build / "SwiftlightVideo.build").glob("*.swift.o"))
    # Snapshots retain the exact archive and header used by the wrapper baseline.
    archive = build / "libMoonlightAppleVideo.a"
    command = [swiftc, "-swift-version", "6", "-parse-as-library", "-target", target,
               "-sdk", sdk, "-module-cache-path", str(directory / "module-cache"),
               "-I", str(build / "Modules")]
    snapshot = (build / "native-include/module.modulemap").is_file()
    if snapshot:
        command += ["-Xcc", f"-fmodule-map-file={build / 'native-include/module.modulemap'}",
                    "-Xcc", "-I", "-Xcc", str(build / "native-include")]
    else:
        # Module map options are generated by SwiftPM for all production bridges.
        modulemaps = []
        for index, argument in enumerate(arguments):
            if argument == "-Xcc" and index + 1 < len(arguments):
                following = arguments[index + 1]
                if following.startswith("-fmodule-map-file="):
                    modulemaps.append(Path(following.split("=", 1)[1]))
        for name in ["CPyrowaveBridge", "CMetalPyrowave", "CNativeVideoABI"]:
            modulemap = build / f"{name}.build/module.modulemap"
            if modulemap.is_file():
                modulemaps.append(modulemap)
        for modulemap in dict.fromkeys(modulemaps):
            command += ["-Xcc", f"-fmodule-map-file={modulemap}", "-Xcc", "-I", "-Xcc", str(modulemap.parent)]
    if snapshot:
        if not archive.is_file():
            parser.error("The wrapper snapshot must include its matching native archive")
        objects.append(archive)
    else:
        # Use SwiftPM's current link list. Incremental build directories can retain
        # obsolete native objects and a stale static product from a previous pin.
        link_lists = [build / "swiftlight-replay.product/Objects.LinkFileList",
                      build / "SwiftlightPackageTests.product/Objects.LinkFileList"]
        link_list = next((path for path in link_lists if path.is_file()), None)
        if link_list is None:
            parser.error("Build swiftlight-replay or run SwiftPM tests to create the production link list")
        native_targets = {"MoonlightAppleVideo.build", "CPyrowaveBridge.build", "CMetalPyrowave.build", "CNativeVideoABI.build"}
        objects += [Path(line) for line in link_list.read_text().splitlines()
                    if any(part in native_targets for part in Path(line).parts)]
    command += [str(source), *map(str, objects)]
    command += ["-lc++", "-o", str(executable)]
    for framework in ["Foundation", "QuartzCore", "Metal", "CoreVideo", "CoreMedia", "VideoToolbox", "IOSurface"]:
        command += ["-framework", framework]
    subprocess.run(command, check=True, timeout=120)
    print(executable)
    if args.compile_only:
        return 0
    subprocess.run([str(executable), str(args.fixture.resolve()), str(args.fps), str(args.frames),
                    str(args.warmup), str(args.depth), str(args.output.resolve())], check=True, timeout=60)
    report = json.loads(args.output.read_text())
    report["harness_sha256"] = hashlib.sha256(source.read_bytes()).hexdigest()
    report["build_directory"] = str(build)
    args.output.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
